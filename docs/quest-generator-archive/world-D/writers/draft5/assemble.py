"""Assemble spines.md (draft 5) from draft5/base.md and the per-spine patches.

base.md is draft 4 with small in-place fixes. Each draft5/<SID>.md patch holds
whole replacement fields, each opened by a line '@@ N' (N = field number);
fields 11 and 18 are new in draft 5. Field 17 is regenerated by the roller
(`roll_samples.py --placing`) when `--placing` is passed.

Run:  python3 draft5/assemble.py            (fields from the patches)
      python3 draft5/assemble.py --placing  (then field 17 from the roller)
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "spines.md")
FIELD = re.compile(r"^\*\*(\d+) · ", re.M)


def split_fields(body):
    """{n: text} for a spine section's body, plus its lead (before field 1)."""
    ms = list(FIELD.finditer(body))
    lead = body[:ms[0].start()] if ms else body
    out = {}
    for i, m in enumerate(ms):
        end = ms[i + 1].start() if i + 1 < len(ms) else len(body)
        out[int(m.group(1))] = body[m.start():end].rstrip() + "\n"
    return lead, out


def patches(sid):
    p = os.path.join(HERE, f"{sid}.md")
    if not os.path.exists(p):
        return {}
    txt = open(p, encoding="utf-8").read()
    out = {}
    for m in re.finditer(r"^@@ (\d+)\s*\n(.*?)(?=^@@ \d+\s*$|\Z)", txt, re.M | re.S):
        out[int(m.group(1))] = m.group(2).strip() + "\n"
    return out


def assemble(placing=None):
    md = open(os.path.join(HERE, "base.md"), encoding="utf-8").read()
    secs = list(re.finditer(r"^## (W\d-[AB]) · .*?$", md, re.M))
    tail_at = md.index("\n## Self-check")
    out = [md[:secs[0].start()]]
    for i, m in enumerate(secs):
        end = secs[i + 1].start() if i + 1 < len(secs) else tail_at + 1
        sec = md[m.start():end]
        sid = m.group(1)
        head, body = sec.split("\n", 1)
        body = body.rstrip()
        if body.endswith("---"):
            body = body[:-3].rstrip()
        lead, fields = split_fields(body + "\n")
        fields.update(patches(sid))
        if placing and sid in placing:
            fields[17] = placing[sid].strip() + "\n"
        parts = [head + "\n" + lead.rstrip("\n") + "\n"]
        for n in sorted(fields):
            parts.append("\n" + fields[n].rstrip() + "\n")
        out.append("".join(parts) + "\n---\n\n")
    out.append(md[tail_at + 1:])
    open(OUT, "w", encoding="utf-8").write("".join(out))


if __name__ == "__main__":
    assemble()
    if "--placing" in sys.argv:
        r = subprocess.run([sys.executable, os.path.join(HERE, "..", "roll_samples.py"), "--placing"],
                           capture_output=True, text=True, check=True)
        placing = {m.group(1): m.group(2) for m in
                   re.finditer(r"<!-- (W\d-[AB]) -->\n(.*?)(?=<!-- W\d-[AB] -->|\Z)", r.stdout, re.S)}
        assemble(placing)
    print("spines.md assembled")
